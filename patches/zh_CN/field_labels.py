def label_for(path: str, fallback: str = "") -> str:
    """The page's label, or the app's own when the page has none."""
    orig = (LABEL_OVERRIDE.get(path) or FIELD_LABEL.get(path)
            or EXTRA_LABEL.get(path) or fallback)
    try:
        from spektrafilm_gui.zh_translation import translate_field
        return translate_field(path, orig)
    except Exception:
        return orig


def unit_for(path: str) -> str:
    return FIELD_UNIT.get(path) or EXTRA_UNIT.get(path, "")


def decimals_for(path: str):
    raw = FIELD_DECIMALS.get(path)
    if raw is None:
        raw = EXTRA_DECIMALS.get(path)
    return int(raw) if raw is not None else None


def option_label(slug: str, fallback: str = "") -> str:
    """The page's display name for an option, or the app's own."""
    orig = OPTION_LABEL.get(str(slug)) or fallback or str(slug)
    try:
        from spektrafilm_gui.zh_translation import translate_option
        return translate_option(slug, orig)
    except Exception:
        return orig
